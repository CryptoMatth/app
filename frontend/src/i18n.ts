const DICTS: Record<Lang, Dict> = { it: IT, en: EN };

function interpolate(text: string, params?: Record<string, string | number>): string {
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}

/** Locale used for JavaScript Intl (dates, numbers). */
export function localeOf(lang: Lang | undefined): string {
  return lang === 'en' ? 'en-GB' : 'it-IT';
}

/**
 * Translate a "well-known" default label to the current language.
 * Falls back to the given `storedLabel` when the id/label is custom.
 *
 * Accepts either a canonical id (`primo`, `verdura`) OR the original
 * default Italian label (`Primo`, `Verdura`). Custom user labels are
 * returned as-is.
 */
export function translateDefaultLabel(
  lang: Lang,
  namespace: 'course' | 'cat',
  id: string | undefined | null,
  storedLabel: string,
): string {
  if (!id && !storedLabel) return '';
  const dict = DICTS[lang];
  // If the user has renamed a default category (stored label != default IT
  // label for this id), always prefer their customization — never overwrite
  // it with the built-in translation.
  const defaultItLabel = id ? IT[`${namespace}.${id}`] : undefined;
  const userCustomized = !!defaultItLabel && !!storedLabel &&
    storedLabel.trim().toLowerCase() !== defaultItLabel.trim().toLowerCase();
  if (userCustomized) return storedLabel;
  // Try by id first
  const byId = id ? dict[`${namespace}.${id}`] : undefined;
  if (byId) return byId;
  // Fallback: normalize stored label to id form and try again
  const norm = storedLabel.trim().toLowerCase()
    .replace(/[\s/]+/g, '_')
    .replace(/[^a-z0-9_]/g, '');
  const byLabel = dict[`${namespace}.${norm}`];
  if (byLabel) return byLabel;
  return storedLabel;
}

export function useTranslation() {
  const { prefs } = useAuth();
  const lang: Lang = ((prefs as any)?.language === 'en' ? 'en' : 'it');
  const dict = DICTS[lang];
  function t(key: string, params?: Record<string, string | number>): string {
    const raw = dict[key] ?? IT[key] ?? key;
    return interpolate(raw, params);
  }
  function tCourse(c: { id: string; label: string } | undefined | null): string {
    if (!c) return '';
    return translateDefaultLabel(lang, 'course', c.id, c.label);
  }
  function tCat(c: { id: string; label: string } | undefined | null): string {
    if (!c) return '';
    return translateDefaultLabel(lang, 'cat', c.id, c.label);
  }
  const locale = localeOf(lang);
  return { t, lang, locale, tCourse, tCat };
}

/** Standalone t() used outside of React (rarely). Falls back to Italian. */
export function tStatic(lang: Lang | undefined, key: string, params?: Record<string, string | number>): string {
  const dict = DICTS[lang || 'it'];
  const raw = dict[key] ?? IT[key] ?? key;
  return interpolate(raw, params);
}
